def inr(n):
    s = str(n)
    if len(s) <= 3:
        return s
    head, tail, parts = s[:-3], s[-3:], []
    while len(head) > 2:
        parts.insert(0, head[-2:])
        head = head[:-2]
    if head:
        parts.insert(0, head)
    return ",".join(parts + [tail])


def rdate(r):
    return f"{r.randint(1, 28):02d}-{r.randint(1, 12):02d}-{r.choice([2025, 2026])}"


def make(lang, seed):
    r = random.Random(seed)
    d = L[lang]
    cur = d["cur"]
    ref = f"EHF/HL/2026/{r.randint(10000, 99999)}"
    end = "." if lang == "marathi" else "।"
    blocks = [("h1", r.choice(d["titles"])),
              ("p", f"{d['ref']}: {ref} {d['date']}: {rdate(r)}"),
              ("p", f"{d['sal']} {r.choice(d['first'])} {r.choice(d['last'])}, {d['house']} {r.randint(1, 120)}, "
                    f"{r.choice(d['areas'])}, {r.choice(d['cities'])} {r.randint(110000, 799999)}{end}"),
              ("h2", d["head"])] + [("p", p) for p in r.sample(d["paras"], r.randint(1, 3))]
    if r.random() < 0.55:
        rows = [d["cols"]]
        for lab, kind in r.sample(d["labels"], r.randint(4, 7)):
            v = {"amt": cur + inr(r.randint(5, 9999) * 100),
                 "rate": f"{r.randint(7, 13)}.{r.randint(0, 99):02d}% {d['rate']}",
                 "mon": f"{r.choice([60, 84, 120, 180, 240, 300])} {d['mon']}", "date": rdate(r)}[kind]
            rows.append([lab, v])
    else:
        rows = [d["scols"]] + [[rdate(r), r.choice(d["descs"]), cur + inr(r.randint(1, 99999))] for _ in range(r.randint(4, 7))]
    blocks += [("table", rows), ("p", r.choice(d["foots"]).format(n=r.choice([30, 45, 60, 90])))]
    return blocks


for lang in L:
    for k in range(80):
        blocks = make(lang, k * 7 + len(lang))
        stem = f"{lang}_{k:02d}"
        dpdf = OUT / f"{stem}_digital.pdf"
        digital(html(blocks, "ur" if lang == "urdu" else ""), dpdf)
        hard = k % 2 == 1
        scan(dpdf, OUT / f"{stem}_{'hard' if hard else 'clean'}.pdf", 1000 + k, hard)
        dpdf.unlink()
        lines = []
        for kind, v in blocks:
            lines += [" ".join(c for c in rw if c) for rw in v] if kind == "table" else [v]
        (OUT / f"{stem}.gt.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
        (OUT / f"{stem}.tables.json").write_text(
            json.dumps([v for kd, v in blocks if kd == "table"], ensure_ascii=False), encoding="utf-8")
    print("made", lang)
